def test_confidentiality_extracts_office_and_pdf_inputs_with_bounded_failures(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve protected-source text extraction across supported document formats."""
    docx_path = tmp_path / "source.docx"
    document = Document()
    document.add_paragraph("Docx paragraph")
    table = document.add_table(rows=1, cols=1)
    table.cell(0, 0).text = "Docx table"
    document.save(docx_path)

    xlsx_path = tmp_path / "source.xlsx"
    workbook = Workbook()
    workbook.active.title = "Workbook sheet"
    workbook.active.append(["Cell value", 5])
    workbook.save(xlsx_path)

    pdf_path = tmp_path / "source.pdf"
    pdf = pymupdf.open()
    page = pdf.new_page()
    page.insert_text((72, 72), "PDF source")
    pdf.save(pdf_path)
    pdf.close()

    assert "Docx paragraph" in _extract_docx_text(docx_path)
    assert "Docx table" in extract_text(docx_path)
    assert "Workbook sheet" in _extract_xlsx_text(xlsx_path)
    assert "Cell value" in extract_text(xlsx_path)
    assert "PDF source" in _extract_pdf_text(pdf_path)
    assert "PDF source" in extract_text(pdf_path)

    plain = tmp_path / "source.txt"
    plain.write_bytes(b"plain\xff text")
    assert "plain" in _extract_plain_text(plain)
    monkeypatch.setattr(confidentiality, "MAX_TEXT_BYTES", 1)
    assert extract_text(plain) == ""
    monkeypatch.setattr(confidentiality, "MAX_TEXT_BYTES", 25 * 1024 * 1024)
    assert _digest(tmp_path / "missing.txt") is None
    monkeypatch.setattr(confidentiality, "MAX_HASH_BYTES", 0)
    assert _digest(plain) is None
    monkeypatch.setattr(confidentiality, "MAX_HASH_BYTES", 300 * 1024 * 1024)
    assert _digest(tmp_path) is None


def test_confidentiality_guard_covers_overlap_archive_and_sanitization_branches(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve precise derivative, archive, and user-visible link decisions."""
    workspace = tmp_path / "workspace"
    source = workspace / "private" / "long-report.txt"
    source.parent.mkdir(parents=True)
    source.write_text(restricted_text())
    allowed = workspace / "published.txt"
    allowed.write_text("This is allowed")
    guard = RestrictedContentGuard.build(workspace, ["private/long-report.txt"])
    assert guard.active
    assert guard.is_explicitly_protected("private/long-report.txt")
    assert not guard._substantial_overlap(("short",))
    assert not guard._exceeds_excerpt_limit(("short",))

    unsafe_archive = workspace / "output.zip"
    unsafe_archive.write_bytes(b"not archive")
    assert not guard._archive_contains_source(unsafe_archive)
    empty = RestrictedContentGuard(workspace, ["private"], ())
    assert not empty._archive_contains_source(unsafe_archive)

    text, changed = guard.sanitize_text(
        "Read https://example.test/files/private%2Flong-report.txt and "
        "[copy](https://example.test/long-report-copy.txt)."
    )
    assert changed
    assert "restricted download unavailable" in text
    assert guard._references_sensitive_path("/files/LONG-REPORT.txt")
    assert guard._references_sensitive_path("/files/long-report-copy.txt")
    assert not guard._references_sensitive_path("/files/public.txt")

    candidate = workspace / "outputs" / "allowed-copy.txt"
    candidate.parent.mkdir()
    candidate.write_bytes(allowed.read_bytes())
    before = snapshot_workspace(workspace)
    assert guard._matches_unrestricted_file(
        "outputs/allowed-copy.txt", _digest(candidate), candidate.stat().st_size
    )
    assert not guard._matches_unrestricted_file("outputs/allowed-copy.txt", None, 1)
    candidate.unlink()
    assert guard.remove_generated_derivatives(before) == []

    blocked = workspace / "outputs" / "blocked.txt"
    blocked.write_text(restricted_text())
    before = snapshot_workspace(workspace)
    blocked.write_text(restricted_text() + " changed")
    with monkeypatch.context() as context:
        original_unlink = Path.unlink

        def deny_unlink(path: Path, *args, **kwargs) -> None:
            """Simulate a transient filesystem deletion failure for one derivative."""
            if path == blocked:
                raise OSError("busy")
            original_unlink(path, *args, **kwargs)

        context.setattr(Path, "unlink", deny_unlink)
        assert guard.remove_generated_derivatives(before) == []
    assert blocked.exists()


def test_snapshot_and_derivative_cache_fail_closed_on_workspace_changes(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve metadata snapshots, bounded cache eviction, and mutation fail-closed behavior."""
    workspace = tmp_path / "workspace"
    workspace.mkdir()
    protected = workspace / "private.txt"
    candidate = workspace / "candidate.txt"
    protected.write_text(restricted_text())
    candidate.write_text("safe aggregate")
    symlink = workspace / "source-link.txt"
    symlink.symlink_to(protected)
    assert "source-link.txt" not in snapshot_workspace(workspace)
    assert snapshot_workspace(tmp_path / "missing") == {}
    assert cached_derivative_path_check(workspace, [], "candidate.txt") is False

    confidentiality._DERIVATIVE_CACHE.clear()
    monkeypatch.setattr(confidentiality, "DERIVATIVE_CACHE_ENTRIES", 1)
    assert not cached_derivative_path_check(workspace, ["private.txt"], "candidate.txt")
    candidate.write_text("another safe aggregate")
    assert not cached_derivative_path_check(workspace, ["private.txt"], "candidate.txt")
    assert len(confidentiality._DERIVATIVE_CACHE) == 1

    original_snapshot = confidentiality.snapshot_workspace
    snapshots = iter([original_snapshot(workspace), {}, original_snapshot(workspace)])
    monkeypatch.setattr(confidentiality, "snapshot_workspace", lambda _: next(snapshots))
    confidentiality._DERIVATIVE_CACHE.clear()
    assert cached_derivative_path_check(workspace, ["private.txt"], "candidate.txt") is True


def test_confidentiality_remaining_overlap_archive_and_candidate_branches(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve bounded overlap scanning and candidate-file race protections."""
    workspace = tmp_path / "workspace"
    protected = workspace / "private" / "source.txt"
    protected.parent.mkdir(parents=True)
    protected.write_text(restricted_text())
    guard = RestrictedContentGuard.build(workspace, ["private"])
    assert guard._substantial_overlap(guard.sources[0].words)
    assert guard.derivative_reason(protected) == "exact restricted copy"

    archive = workspace / "output.zip"
    with zipfile.ZipFile(archive, "w") as output:
        output.writestr("folder/", b"")
        output.writestr("copy.txt", protected.read_bytes())
    assert guard._archive_contains_source(archive)
    monkeypatch.setattr(confidentiality, "MAX_HASH_BYTES", 1)
    assert not guard._archive_contains_source(archive)
    monkeypatch.setattr(confidentiality, "MAX_HASH_BYTES", 300 * 1024 * 1024)

    output = workspace / "outputs" / "safe.txt"
    output.parent.mkdir()
    output.write_text("safe")
    candidates = snapshot_workspace(workspace)
    output.write_text("changed")
    assert not guard._matches_unrestricted_file(
        "outputs/safe.txt", _digest(output), output.stat().st_size, candidates
    )
    output.unlink()
    assert not guard._matches_unrestricted_file("outputs/safe.txt", "digest", 1, candidates)
    assert guard.is_derivative_path("outputs") is False

    monkeypatch.setattr(confidentiality, "MAX_SOURCE_FILES", 0)
    assert not RestrictedContentGuard.build(workspace, ["private"]).active


def test_confidentiality_remaining_extraction_overlap_and_snapshot_branches(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve bounded PDF extraction, overlap-only detection, and filesystem-race snapshots."""
    pdf_path = tmp_path / "long.pdf"
    pdf = pymupdf.open()
    pdf.new_page().insert_text((72, 72), "this is long enough PDF content")
    pdf.save(pdf_path)
    pdf.close()
    monkeypatch.setattr(confidentiality, "MAX_TEXT_BYTES", 3)
    assert _extract_pdf_text(pdf_path)
    monkeypatch.setattr(confidentiality, "MAX_TEXT_BYTES", 25 * 1024 * 1024)
    unsupported = tmp_path / "unsupported.bin"
    unsupported.write_text("unsupported")
    assert extract_text(unsupported) == ""

    words = tuple(f"word{index}" for index in range(100))
    overlap_source = RestrictedSource(
        relative_path="private.txt",
        digest=None,
        words=words,
        shingles=_shingles(words),
        prohibited_excerpts=frozenset(),
    )
    guard = RestrictedContentGuard(tmp_path, ["private.txt"], (overlap_source,))
    candidate = tmp_path / "candidate.txt"
    candidate.write_text(" ".join(words))
    assert guard.derivative_reason(candidate) == "substantial restricted-content reproduction"
    short_source = RestrictedSource(
        relative_path="short.txt",
        digest=None,
        words=("short",),
        shingles=frozenset(),
        prohibited_excerpts=frozenset(),
    )
    assert not RestrictedContentGuard(tmp_path, [], (short_source,))._substantial_overlap(words)

    class BrokenFile:
        """Represent a workspace file that disappears before stat succeeds."""

        def is_file(self) -> bool:
            """Initially appear to be a regular file."""
            return True

        def is_symlink(self) -> bool:
            """Report a regular non-symlink input."""
            return False

        def stat(self):
            """Trigger the documented snapshot race handling."""
            raise OSError("gone")

    class BrokenRoot:
        """Expose a single disappearing item through the workspace-root protocol."""

        def exists(self) -> bool:
            """Report an existing workspace root."""
            return True

        def rglob(self, _: str):
            """Yield the disappearing entry."""
            return [BrokenFile()]

    assert snapshot_workspace(BrokenRoot()) == {}
    assert FileStamp(size=1, modified_ns=2) == FileStamp(size=1, modified_ns=2)


def test_confidentiality_remaining_archive_and_candidate_skip_branches(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Preserve non-overlap, invalid archive, symlink, and stale-candidate defensive branches."""
    workspace = tmp_path / "workspace"
    workspace.mkdir()
    source = workspace / "private.txt"
    source.write_text(restricted_text())
    guard = RestrictedContentGuard.build(workspace, ["private.txt"])
    candidate_words = tuple(f"different{index}" for index in range(100))
    assert not guard._substantial_overlap(candidate_words)
    monkeypatch.setattr(confidentiality, "_shingles", lambda _: frozenset())
    assert not guard._substantial_overlap(tuple(f"word{index}" for index in range(100)))
    monkeypatch.undo()

    symlink = workspace / "linked-directory"
    target = tmp_path / "target"
    target.mkdir()
    symlink.symlink_to(target, target_is_directory=True)
    assert _regular_files(symlink) == []

    archive = workspace / "invalid.zip"
    archive.write_bytes(b"invalid")
    monkeypatch.setattr(confidentiality.zipfile, "is_zipfile", lambda _: True)
    assert not guard._archive_contains_source(archive)

    valid_archive = workspace / "mixed.zip"
    with zipfile.ZipFile(valid_archive, "w") as output:
        output.writestr("safe.txt", b"safe")
        output.writestr("copy.txt", source.read_bytes())
    assert guard._archive_contains_source(valid_archive)

    other = workspace / "other.txt"
    other.write_text("same")
    copied = workspace / "copied.txt"
    copied.write_text("same")
    candidates = {"other.txt": FileStamp(size=4, modified_ns=other.stat().st_mtime_ns)}
    other.unlink()
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)
    other.symlink_to(copied)
    candidates = {"other.txt": FileStamp(size=4, modified_ns=other.stat().st_mtime_ns)}
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)

    stable = workspace / "stable.txt"
    stable.write_text("other")
    candidates = {"stable.txt": FileStamp(size=5, modified_ns=stable.stat().st_mtime_ns)}
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)

    stable.write_text("else")
    candidates = {"stable.txt": FileStamp(size=4, modified_ns=stable.stat().st_mtime_ns)}
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)

    changed = workspace / "changed.txt"
    changed.write_text("same")
    candidates = {"changed.txt": FileStamp(size=4, modified_ns=changed.stat().st_mtime_ns)}
    changed.write_text("else")
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)

    original_stat = Path.stat
    stable_stat_calls = 0

    def disappearing_stat(path: Path, *args, **kwargs):
        """Simulate a candidate disappearing after the snapshot was captured."""
        nonlocal stable_stat_calls
        if path == stable:
            stable_stat_calls += 1
            if stable_stat_calls > 2:
                raise OSError("gone")
        return original_stat(path, *args, **kwargs)

    stable.write_text("same")
    candidates = {"stable.txt": FileStamp(size=4, modified_ns=stable.stat().st_mtime_ns)}
    monkeypatch.setattr(Path, "stat", disappearing_stat)
    assert not guard._matches_unrestricted_file("copied.txt", _digest(copied), 4, candidates)
