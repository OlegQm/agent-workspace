def restricted_text() -> str:
    """Return sufficiently long deterministic confidential text for overlap tests."""
    return " ".join(
        f"confidential customer record number {index} contains private settlement details"
        for index in range(40)
    )


def test_exact_restricted_copy_is_removed(tmp_path: Path) -> None:
    """Verify that a generated byte-for-byte copy cannot remain downloadable."""
    workspace = tmp_path / "workspace"
    protected = workspace / "private" / "source.txt"
    protected.parent.mkdir(parents=True)
    protected.write_text(restricted_text())
    guard = RestrictedContentGuard.build(workspace, ["private/source.txt"])
    before = snapshot_workspace(workspace)

    output = workspace / "outputs" / "copy.txt"
    output.parent.mkdir()
    output.write_bytes(protected.read_bytes())

    blocked = guard.remove_generated_derivatives(before)

    assert [(item.relative_path, item.reason) for item in blocked] == [
        ("outputs/copy.txt", "exact restricted copy")
    ]
    assert not output.exists()


