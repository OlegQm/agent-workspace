def test_derivative_decision_is_cached_and_invalidated(tmp_path: Path, monkeypatch) -> None:
    """Reuse a stable derivative decision and invalidate it after a file change."""
    workspace = tmp_path / "workspace"
    protected = workspace / "private" / "source.txt"
    candidate = workspace / "outputs" / "summary.txt"
    protected.parent.mkdir(parents=True)
    candidate.parent.mkdir(parents=True)
    protected.write_text(restricted_text())
    candidate.write_text("The report contains a limited aggregate.")
    calls = 0

    from features.workspace.infrastructure.confidentiality import guard as confidentiality

    original = confidentiality.extract_text

    def counted_extract_text(path: Path) -> str:
        """Count expensive document extraction calls in the cache test."""
        nonlocal calls
        calls += 1
        return original(path)

    monkeypatch.setattr(confidentiality, "extract_text", counted_extract_text)

    assert not cached_derivative_path_check(
        workspace,
        ["private/source.txt"],
        "outputs/summary.txt",
    )
    first_calls = calls
    assert not cached_derivative_path_check(
        workspace,
        ["private/source.txt"],
        "outputs/summary.txt",
    )
    assert calls == first_calls

    candidate.write_text(restricted_text())
    assert cached_derivative_path_check(
        workspace,
        ["private/source.txt"],
        "outputs/summary.txt",
    )
    assert calls > first_calls


